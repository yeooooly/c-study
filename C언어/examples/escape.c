#include <stdio.h>

int main(void)
{
    printf("Be happy\n");                  // \n : 줄바꿈
    printf("12345678901234567890\n");
    printf("My\tfriend\n");                // \t : 탭
    printf("Goot\bd\tchance\n");           // \b : 한 칸 뒤로 -> Good
    printf("Cow\rW\a\n");                  // \r : 줄 맨 앞으로 -> Wow, \a : 경고음
    return 0;
}
